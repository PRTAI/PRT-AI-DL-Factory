"""TRL command builder.

Two shapes of RL job are supported:

1. **Agentic RL on a Harbor task tree** — ``trl.experimental.harbor.HarborSpec``
   turns a task suite into ``train_dataset`` / ``environment_factory`` /
   ``reward_funcs``, and the reward is the Harbor verifier's scalar. This is the
   path to take when the data is in Harbor format.
2. **Classic GRPO/GSPO/RLOO/DPO on tabular data** — json / jsonl / parquet with a
   ``prompt`` column (plus ``chosen``/``rejected`` for DPO).

Both are emitted as a generated, self-contained training script so the exact run
is reproducible from the job work dir.
"""

from __future__ import annotations

import os
from pathlib import Path

from ..config import settings
from ..models import DatasetKind, Job, RLConfig, TrainStage
from ..services import dataset_service
from ..store import store
from .base import BuildError, BuildResult, resolve_attn_implementation

# 组相对算法：num_generations 是「组大小」，生成批次必须是它的整数倍
_GROUP_ALGOS = {TrainStage.GRPO, TrainStage.DAPO, TrainStage.GSPO, TrainStage.RLOO}

_SUPPORTED = {
    TrainStage.GRPO,
    TrainStage.DAPO,
    TrainStage.GSPO,
    TrainStage.RLOO,
    TrainStage.DPO,
    TrainStage.KTO,
}

HARBOR_SCRIPT = '''"""Generated by PRT AI DL Factory — TRL GRPO over a Harbor task suite.

Job:   {job_id} ({job_name})
Model: {model_path}
Tasks: {tasks_root}
"""

from trl import GRPOConfig, GRPOTrainer
from trl.experimental.harbor import HarborSpec
{peft_import}
CONFIG = {config_json}
{peft_block}

def main() -> None:
    spec = HarborSpec(
        {tasks_root!r},
        agent={harness!r},
        environment_type={environment_type!r},
        num_tasks={num_tasks!r},
    )
    trainer = GRPOTrainer(
        model={model_path!r},
        args=GRPOConfig(**CONFIG),
        train_dataset=spec.train_dataset,
        environment_factory=spec.environment_factory,
        reward_funcs=spec.reward_funcs,{peft_kwarg}
    )
    trainer.train()
    trainer.save_model(CONFIG["output_dir"])


if __name__ == "__main__":
    main()
'''

TABULAR_SCRIPT = '''"""Generated by PRT AI DL Factory — TRL {trainer_name}.

Job:   {job_id} ({job_name})
Model: {model_path}
Data:  {data_files}
"""

import re

from datasets import load_dataset
from trl import {trainer_name}, {config_name}
{peft_import}
CONFIG = {config_json}
DATA_FILES = {data_files_json}
EVAL_FILES = {eval_files_json}
{peft_block}

def _load(files):
    if not files:
        return None
    suffix = files[0].rsplit(".", 1)[-1].lower()
    loader = "parquet" if suffix == "parquet" else "json"
    return load_dataset(loader, data_files=files, split="train")


{reward_block}


def main() -> None:
    train_dataset = _load(DATA_FILES)
    eval_dataset = _load(EVAL_FILES)
    kwargs = dict(
        model={model_path!r},
        args={config_name}(**CONFIG),
        train_dataset=train_dataset,
    )
    if eval_dataset is not None:
        kwargs["eval_dataset"] = eval_dataset
{peft_assign}{reward_kwarg}
    trainer = {trainer_name}(**kwargs)
    trainer.train()
    trainer.save_model(CONFIG["output_dir"])


if __name__ == "__main__":
    main()
'''

DEFAULT_REWARD_BLOCK = '''def _extract(text: str) -> str:
    match = re.findall(r"<answer>(.*?)</answer>", text, re.S)
    if match:
        return match[-1].strip()
    return text.strip().splitlines()[-1].strip() if text.strip() else ""


def outcome_reward(completions, **kwargs):
    """Exact-match reward against the ground-truth column."""
    targets = None
    for key in ("ground_truth", "answer", "solution", "label"):
        if key in kwargs and kwargs[key] is not None:
            targets = kwargs[key]
            break
    if targets is None:
        return [0.0 for _ in completions]
    rewards = []
    for completion, target in zip(completions, targets):
        text = completion if isinstance(completion, str) else completion[-1].get("content", "")
        rewards.append(1.0 if _extract(text) == str(target).strip() else 0.0)
    return rewards
'''


def build(job: Job, work_dir: Path, output_dir: Path) -> BuildResult:
    config: RLConfig = job.rl  # type: ignore[assignment]
    if config is None:
        raise BuildError("缺少 RL 配置")
    if config.algorithm not in _SUPPORTED:
        raise BuildError(f"TRL 不支持算法 {config.algorithm.value}")

    root = settings.trl_root
    if not (root / "trl").is_dir():
        raise BuildError(f"TRL 源码目录无效: {root}")

    dataset = store.datasets.get(config.dataset_id)
    if dataset is None:
        raise BuildError(f"数据集不存在: {config.dataset_id}")

    n_gpus = max(1, job.resources.n_gpus)
    use_harbor = config.harbor.enabled or dataset.kind == DatasetKind.HARBOR_TASKS
    notes: list[str] = []
    extra_files: dict[str, str] = {}
    harbor_pythonpath: list[str] = []
    peft = _peft_snippets(config, notes)
    # 必须在渲染脚本之前定下来：配置是以字面量嵌进生成脚本里的，
    # 渲染完再改 dict 不会反映到脚本内容里。
    attn, attn_note = resolve_attn_implementation(
        config.attn_implementation, settings.python_for("trl")
    )

    if use_harbor:
        if dataset.kind != DatasetKind.HARBOR_TASKS:
            raise BuildError("Harbor 环境模式需要 harbor_tasks 类型的数据集")
        if not (root / "trl" / "experimental" / "harbor").is_dir():
            raise BuildError("当前 TRL 版本不包含 trl.experimental.harbor 集成")
        if config.algorithm not in {TrainStage.GRPO, TrainStage.DAPO, TrainStage.GSPO}:
            raise BuildError("Harbor 环境模式目前只支持 GRPO / GSPO")
        script_name = "train_harbor_grpo.py"
        harbor_files, harbor_meta_dir = _harbor_import_files(notes)
        extra_files.update(harbor_files)
        harbor_pythonpath = [str(work_dir / harbor_meta_dir), str(settings.harbor_root / "src")]
        trainer_config = _drop_unknown_keys(
            _grpo_config(job, config, output_dir, agentic=True, attn=attn), "GRPOConfig", notes
        )
        script = HARBOR_SCRIPT.format(
            **peft,
            job_id=job.id,
            job_name=job.name,
            model_path=config.model_path,
            tasks_root=dataset.root_path,
            harness=config.harbor.harness,
            environment_type=config.harbor.environment_type,
            num_tasks=config.harbor.num_tasks,
            config_json=_pretty(trainer_config),
        )
        notes.append(
            f"Harbor agentic RL：harness={config.harbor.harness}，沙箱={config.harbor.environment_type}，"
            f"任务数={config.harbor.num_tasks or dataset.stats.n_tasks}"
        )
        notes.append("奖励直接来自 Harbor verifier 的 reward 标量。")
        if config.harbor.environment_type == "docker":
            notes.append("需要本机 Docker 守护进程可用，并预留足够的并发容器配额。")
    else:
        trainer_name, config_name = _trainer_for(config.algorithm)
        data_files, eval_files = _tabular_files(dataset, config)
        trainer_config = _drop_unknown_keys(
            _grpo_config(job, config, output_dir, agentic=False, attn=attn)
            if trainer_name in {"GRPOTrainer", "RLOOTrainer"}
            else _preference_config(job, config, output_dir, attn=attn),
            config_name,
            notes,
        )
        if trainer_name in {"GRPOTrainer", "RLOOTrainer"}:
            if config.custom_reward_function_path:
                reward_block = (
                    f"import importlib.util as _ilu\n"
                    f"_spec = _ilu.spec_from_file_location('prt_reward', {config.custom_reward_function_path!r})\n"
                    f"_mod = _ilu.module_from_spec(_spec)\n"
                    f"_spec.loader.exec_module(_mod)\n"
                    f"outcome_reward = getattr(_mod, {(config.custom_reward_function_name or 'reward')!r})\n"
                )
                notes.append(f"使用自定义奖励函数: {config.custom_reward_function_path}")
            else:
                reward_block = DEFAULT_REWARD_BLOCK
                notes.append("使用内置精确匹配奖励（ground_truth / answer / solution / label 列）。")
            reward_kwarg = '    kwargs["reward_funcs"] = outcome_reward\n'
        else:
            reward_block = ""
            reward_kwarg = ""
        script_name = f"train_{config.algorithm.value}.py"
        script = TABULAR_SCRIPT.format(
            **peft,
            trainer_name=trainer_name,
            config_name=config_name,
            job_id=job.id,
            job_name=job.name,
            model_path=config.model_path,
            data_files=", ".join(data_files),
            data_files_json=_pretty(data_files),
            eval_files_json=_pretty(eval_files),
            config_json=_pretty(trainer_config),
            reward_block=reward_block,
            reward_kwarg=reward_kwarg,
        )

    python_bin = settings.python_for("trl")
    if n_gpus > 1:
        command = [
            python_bin,
            "-m",
            "accelerate.commands.launch",
            "--num_processes",
            str(n_gpus),
            "--mixed_precision",
            "bf16",
            script_name,
        ]
        notes.append(f"多卡训练：accelerate launch --num_processes {n_gpus}")
    else:
        command = [python_bin, script_name]

    # trl 检出放最前面，保证跑的是团队那份代码；harbor 的两条只提供 harbor 包与它的元数据，
    # 不含其他包，不会遮蔽 trl 环境里已装好的依赖。
    env = {
        "PYTHONPATH": os.pathsep.join([str(root), *harbor_pythonpath]),
        "TOKENIZERS_PARALLELISM": "false",
        "ACCELERATE_LOG_LEVEL": "info",
    }
    notes.insert(0, f"TRL {config.algorithm.value.upper()}，{n_gpus} GPU")
    if config.algorithm in _GROUP_ALGOS:
        per_device, accum, effective = _group_batch(config.train_batch_size, config.rollout.n, n_gpus)
        notes.append(
            f"批次换算：每卡 batch {per_device}（= 组大小，保证生成批次里都是完整的组）× "
            f"{n_gpus} 卡 × 梯度累积 {accum} → 每轮 {effective} 个 prompt、"
            f"{effective * config.rollout.n} 条采样"
            + ("" if effective == config.train_batch_size else f"（填的是 {config.train_batch_size}，已向上取整到卡数的整数倍）")
        )
    if attn_note:
        notes.append(f"{attn_note}（走 model_init_kwargs）")

    return BuildResult(
        command=command,
        cwd=str(work_dir),
        env=env,
        files={script_name: script, **extra_files},
        output_dir=str(output_dir),
        notes=notes,
    )


# --------------------------------------------------------------------------- #
def _trainer_for(algorithm: TrainStage) -> tuple[str, str]:
    return {
        TrainStage.GRPO: ("GRPOTrainer", "GRPOConfig"),
        TrainStage.DAPO: ("GRPOTrainer", "GRPOConfig"),
        TrainStage.GSPO: ("GRPOTrainer", "GRPOConfig"),
        TrainStage.RLOO: ("RLOOTrainer", "RLOOConfig"),
        TrainStage.DPO: ("DPOTrainer", "DPOConfig"),
        TrainStage.KTO: ("KTOTrainer", "KTOConfig"),
    }[algorithm]


def _tabular_files(dataset, config: RLConfig) -> tuple[list[str], list[str]]:
    root = Path(dataset.root_path)
    if dataset.kind == DatasetKind.VERL_PARQUET:
        meta = dataset_service.read_meta(dataset)
        train = meta.get("train_files") or []
        evals = meta.get("val_files") or []
    else:
        train = [str(root / f.path) for f in dataset.files if f.role in {"train", "data"}]
        evals = [str(root / f.path) for f in dataset.files if f.role == "eval"]
    if not train:
        raise BuildError("数据集中没有可用的训练文件")
    if config.eval_dataset_id:
        eval_dataset = store.datasets.get(config.eval_dataset_id)
        if eval_dataset is not None:
            evals = [str(Path(eval_dataset.root_path) / f.path) for f in eval_dataset.files]
    return train, evals


def _peft_snippets(config: RLConfig, notes: list[str]) -> dict[str, str]:
    """LoRA 的三段代码：import、PEFT_CONFIG 常量、传给 Trainer 的关键字。

    TRL 的 GRPO/RLOO/DPO/KTO Trainer 都接 ``peft_config``（见各 trainer 的 __init__），
    字段名以本机 peft 的 ``LoraConfig`` dataclass 为准。
    """
    if config.finetuning_type != "lora":
        return {"peft_import": "", "peft_block": "", "peft_kwarg": "", "peft_assign": ""}

    spec = config.lora
    # target_modules: "all" -> peft 的 "all-linear"；否则按逗号分隔的列表
    target = spec.target.strip()
    if target in {"", "all"}:
        modules: object = "all-linear"
    else:
        modules = [item.strip() for item in target.split(",") if item.strip()]
    lora_kwargs = {
        "r": spec.rank,
        "lora_alpha": spec.alpha,
        "lora_dropout": spec.dropout,
        "target_modules": modules,
        "task_type": "CAUSAL_LM",
    }
    notes.append(
        f"LoRA：rank {spec.rank} / alpha {spec.alpha} / dropout {spec.dropout} / "
        f"target {modules if isinstance(modules, str) else ','.join(modules)}"
        "（只训练适配器，显存与优化器状态都低一个量级）"
    )
    return {
        "peft_import": "from peft import LoraConfig\n",
        "peft_block": f"PEFT_CONFIG = LoraConfig(**{_pretty(lora_kwargs)})\n",
        "peft_kwarg": "\n        peft_config=PEFT_CONFIG,",
        "peft_assign": '    kwargs["peft_config"] = PEFT_CONFIG\n',
    }


def _harbor_import_files(notes: list[str]) -> tuple[dict[str, str], str]:
    """让 trl 环境能 ``import harbor``。

    Harbor agentic RL 是在**训练进程内**起沙箱的（``HarborSpec`` →
    ``harbor.environments.factory``），所以 harbor 必须能被 trl 那个解释器导入。
    但不能往 trl 环境里 pip install harbor：它会把 openai 3.8 降到 2.54、
    websockets 17 降到 15，而 vllm 依赖这两个。

    所以照平台一贯的做法——代码走 PYTHONPATH 指向团队检出。唯一的坎是
    ``harbor/__init__.py`` 会 ``importlib.metadata.version("harbor")``，光有代码会
    ``PackageNotFoundError``；这里顺手在工作目录里生成一份最小的 ``.dist-info``，
    版本号取自检出自己的 pyproject。

    返回 ``(要写进工作目录的文件, 相对的元数据目录名)``。
    """
    src = settings.harbor_root / "src"
    if not (src / "harbor").is_dir():
        raise BuildError(
            f"Harbor 源码目录无效: {settings.harbor_root}（Harbor 环境模式需要在训练进程内 import harbor）"
        )

    version = ""
    pyproject = settings.harbor_root / "pyproject.toml"
    if pyproject.is_file():
        try:
            import tomllib

            version = str(tomllib.loads(pyproject.read_text(encoding="utf-8"))["project"]["version"])
        except Exception:  # noqa: BLE001 - 版本号读不到不该拦住任务
            version = ""
    version = version or "0.0.0"

    meta_dir = "harbor_meta"
    files = {
        f"{meta_dir}/harbor-{version}.dist-info/METADATA": (
            f"Metadata-Version: 2.1\nName: harbor\nVersion: {version}\n"
        ),
    }
    notes.append(
        f"harbor {version} 通过 PYTHONPATH 指向检出（不装进 trl 环境，避免把 openai/websockets 降级）"
    )
    return files, meta_dir


def _group_batch(prompts: int, group_size: int, n_gpus: int) -> tuple[int, int, int]:
    """把「每轮多少 prompt + 组大小」翻译成 TRL 的三个批次参数。

    TRL 里 ``generation_batch_size = per_device_train_batch_size × 卡数 × steps_per_generation``
    （后者默认取 ``gradient_accumulation_steps``），而且**必须能被 num_generations 整除**
    ——生成批次里不能出现半个组。直接把 prompt 数当每卡 batch 会炸：
    ``generation_batch_size (2) must be divisible by num_generations (8)``。

    所以让每卡每步正好跑一个完整的组，用梯度累积去凑 prompt 数。
    返回 ``(每卡 batch, 梯度累积, 实际每轮 prompt 数)``。
    """
    per_device = group_size
    accum = max(1, -(-prompts // n_gpus))  # 向上取整，至少 1
    return per_device, accum, accum * n_gpus


def _grpo_config(job: Job, config: RLConfig, output_dir: Path, *, agentic: bool, attn: str) -> dict:
    n_gpus = max(1, job.resources.n_gpus)
    per_device, accum, _ = _group_batch(config.train_batch_size, config.rollout.n, n_gpus)
    cfg: dict = {
        "output_dir": str(output_dir),
        "learning_rate": config.learning_rate,
        "per_device_train_batch_size": per_device,
        "gradient_accumulation_steps": accum,
        "num_generations": config.rollout.n,
        # 本机这版 TRL 已经没有 max_prompt_length（GRPOConfig 只剩 max_completion_length，
        # prompt 由 trainer 按 truncation_side="left" 处理），发了会直接 TypeError。
        "max_completion_length": config.max_response_length,
        "num_train_epochs": config.total_epochs,
        "temperature": config.rollout.temperature,
        "top_p": config.rollout.top_p,
        "beta": config.kl_loss_coef if config.use_kl_loss else 0.0,
        "epsilon": config.clip_ratio_low,
        "epsilon_high": config.clip_ratio_high,
        "logging_steps": 1,
        "save_steps": config.save_freq,
        "bf16": True,
        "gradient_checkpointing": config.gradient_checkpointing,
        "log_completions": True,
        "report_to": "none",
    }
    if config.total_training_steps:
        cfg["max_steps"] = config.total_training_steps
    if config.algorithm != TrainStage.RLOO:
        # loss_type / importance_sampling_level 是 GRPOConfig 独有的，RLOOConfig 没有
        cfg["loss_type"] = "dapo" if config.algorithm == TrainStage.DAPO else "bnpo"
    if config.algorithm == TrainStage.GSPO:
        cfg["importance_sampling_level"] = "sequence"
    if config.rollout.backend == "vllm":
        cfg["use_vllm"] = True
        cfg["vllm_mode"] = "colocate"
        cfg["vllm_gpu_memory_utilization"] = config.rollout.gpu_memory_utilization
    if agentic:
        cfg["max_tool_calling_iterations"] = config.harbor.max_tool_calling_iterations
        cfg["chat_template_kwargs"] = {"enable_thinking": False}
    _apply_attn(cfg, attn)
    cfg.update(config.extra_args)
    return cfg


def _preference_config(job: Job, config: RLConfig, output_dir: Path, *, attn: str) -> dict:
    n_gpus = max(1, job.resources.n_gpus)
    cfg = {
        "output_dir": str(output_dir),
        "learning_rate": config.learning_rate,
        "per_device_train_batch_size": max(1, config.train_batch_size // n_gpus),
        "gradient_accumulation_steps": 1,
        "num_train_epochs": config.total_epochs,
        # DPO/KTO 只有 max_length（prompt+response 总长），没有单独的 max_prompt_length
        "max_length": config.max_prompt_length + config.max_response_length,
        "logging_steps": 10,
        "save_steps": config.save_freq,
        "bf16": True,
        "gradient_checkpointing": config.gradient_checkpointing,
        "report_to": "none",
    }
    _apply_attn(cfg, attn)
    cfg.update(config.extra_args)
    return cfg


def _apply_attn(cfg: dict, attn: str) -> None:
    """TRL 没有 attention 参数，实现要走 ``model_init_kwargs`` 透传给 ``from_pretrained``。"""
    if not attn:
        return
    kwargs = dict(cfg.get("model_init_kwargs") or {})
    kwargs["attn_implementation"] = attn
    cfg["model_init_kwargs"] = kwargs


_FIELD_CACHE: dict[str, tuple[float, set[str]]] = {}


def _declared_fields(path: Path, class_name: str) -> set[str]:
    """解析某个 dataclass 声明的字段名（按 mtime 缓存）。"""
    import ast

    try:
        mtime = path.stat().st_mtime
    except OSError:
        return set()
    key = f"{path}|{class_name}"
    cached = _FIELD_CACHE.get(key)
    if cached and cached[0] == mtime:
        return cached[1]
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (OSError, SyntaxError):
        return set()
    fields: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name == class_name:
            fields = {
                item.target.id
                for item in node.body
                if isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name)
            }
            break
    _FIELD_CACHE[key] = (mtime, fields)
    return fields


def _known_config_keys(config_name: str) -> set[str]:
    """``<Xxx>Config`` 自己的字段 + 继承来的 ``TrainingArguments`` 字段。

    TRL 各版本之间这些字段改得很勤（本机这版就把 ``max_prompt_length`` 整个拿掉了，
    ``loss_type`` 也只有 GRPOConfig 有）。发一个它不认识的键，任务会在
    ``XxxConfig(**CONFIG)`` 那一行直接 TypeError —— 而那已经是排队拿到 GPU 之后了。
    """
    trainer_dir = settings.trl_root / "trl" / "trainer"
    # GRPOConfig -> grpo_config.py
    stem = config_name.removesuffix("Config").lower()
    own = _declared_fields(trainer_dir / f"{stem}_config.py", config_name)
    if not own:
        return set()  # 解析不出来就不过滤，别帮倒忙

    base: set[str] = set()
    interpreter = Path(settings.python_for("trl"))
    if interpreter.is_absolute():
        for candidate in sorted(interpreter.resolve().parents[1].glob(
            "lib/python3*/site-packages/transformers/training_args.py"
        )):
            base |= _declared_fields(candidate, "TrainingArguments")
    return own | base


def _drop_unknown_keys(cfg: dict, config_name: str, notes: list[str]) -> dict:
    known = _known_config_keys(config_name)
    if not known:
        return cfg
    unknown = [key for key in cfg if key not in known]
    if unknown:
        notes.append(
            f"以下参数在本机这版 TRL 的 {config_name} 里不存在，已跳过：{', '.join(sorted(unknown))}"
        )
    return {key: value for key, value in cfg.items() if key in known}


def _pretty(payload: object) -> str:
    """把配置渲染成 **Python** 字面量嵌进生成脚本。

    之前用的是 json.dumps —— JSON 的 true / false / null 在 Python 源码里是未定义的名字，
    真跑时第一行 ``"bf16": true`` 就 NameError。测试会把生成的脚本 compile 一遍。
    """
    import pprint

    return pprint.pformat(payload, indent=4, width=100, sort_dicts=False)
