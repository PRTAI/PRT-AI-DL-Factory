def list_deployments(*, active_only: bool = False, project_id: str = "") -> list[Deployment]:
    def keep(item: Deployment) -> bool:
        if active_only and not item.status.is_active:
            return False
        if project_id and item.project_id != project_id:
            return False
        return True

    items = store.deployments.find(keep)
    items.sort(key=lambda d: d.created_at, reverse=True)
    return items


def get_deployment(deployment_id: str) -> Deployment:
    item = store.deployments.get(deployment_id)
    if item is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="部署不存在")
    return item


def busy_gpu_ids() -> set[int]:
    """给调度器用：正在服务的部署占着的 GPU 不能再分给训练任务。"""
    busy: set[int] = set()
    for item in store.deployments.find(lambda d: d.status.is_active):
        busy.update(item.gpu_ids)
    return busy


def endpoints() -> list[dict]:
    """评测表单用的下拉数据。

    给两类地址：``base_url`` 是回环地址（平台自己探活、本机 curl 用），
    ``sandbox_base_url`` / ``sandbox_endpoints`` 用宿主机的实际 IP —— Harbor 的
    agent 跑在容器里，容器内的 127.0.0.1 是容器自己，拿回环地址去评测必然连不上。
    """
    return [
        {
            "id": item.id,
            "name": item.name,
            "model": item.served_model_name,
            "base_url": item.base_url,
            "sandbox_base_url": f"http://{host_address()}:{item.port}/v1",
            "api_protocol": item.api_protocol,
            "supported_protocols": list(PROTOCOL_SUPPORT[item.api_protocol]),
            "sandbox_endpoints": sandbox_endpoints(item),
            "status": item.status.value,
            "api_key": "***" if item.config.api_key else "",
        }
        for item in list_deployments(active_only=True)
    ]


def sandbox_endpoints(item: Deployment) -> dict[str, str]:
    """容器内可达的各接口地址：OpenAI 系带 /v1，Anthropic 客户端自己拼 /v1/messages。"""
    root = f"http://{host_address()}:{item.port}"
    return {protocol: root if protocol == "anthropic" else f"{root}/v1" for protocol in PROTOCOL_SUPPORT[item.api_protocol]}


def resolve_for_agent(deployment_id: str, *, model_style: str, protocol: str | None) -> ResolvedModel:
    """把本地部署翻译成 Harbor 的 ``--model`` + 标准环境变量（与模型配置同一套约定）。"""
    item = store.deployments.get(deployment_id)
    if item is None:
        raise HTTPException(status.HTTP_400_BAD_REQUEST, detail="所选本地部署不存在（可能已删除）")
    if item.status != DeploymentStatus.SERVING:
        raise HTTPException(
            status.HTTP_400_BAD_REQUEST,
            detail=f"本地部署「{item.name}」当前不在服务中（{item.status.value}），请等待就绪或换一个部署",
        )
    wire = protocol or "openai"
    if wire not in PROTOCOL_SUPPORT[item.api_protocol]:
        raise HTTPException(
            status.HTTP_400_BAD_REQUEST,
            detail=f"本地部署「{item.name}」提供的是 {PROTOCOL_LABELS[item.api_protocol]} 接口，"
            f"当前 agent 需要 {PROTOCOL_LABELS[wire]}；请在「模型部署」选择对应接口重新部署",
        )
    served = item.served_model_name
    if wire == "responses" and "/" in served:
        # codex 会把 --model 按 / 切开只留最后一段，发给 vLLM 的模型名就对不上了
        raise HTTPException(status.HTTP_400_BAD_REQUEST, detail=f"codex 不支持带 / 的模型名「{served}」，请修改部署的对外模型名")
    url = sandbox_endpoints(item)[wire]
    key = item.config.api_key or NO_AUTH_PLACEHOLDER
    if wire == "anthropic":
        env = {"ANTHROPIC_API_KEY": key, "ANTHROPIC_BASE_URL": url}
        # claude-code 的后台小任务 / 子 agent 默认用 haiku 等官方模型名，本地只有一个模型
        for name in ("ANTHROPIC_DEFAULT_OPUS_MODEL", "ANTHROPIC_DEFAULT_SONNET_MODEL",
                     "ANTHROPIC_DEFAULT_HAIKU_MODEL", "ANTHROPIC_SMALL_FAST_MODEL", "CLAUDE_CODE_SUBAGENT_MODEL"):
            env[name] = served
        env["CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC"] = "1"
    else:
        env = {"OPENAI_API_KEY": key, "OPENAI_BASE_URL": url, "OPENAI_API_BASE": url}
    model = served if model_style != "litellm" else f"{'anthropic' if wire == 'anthropic' else 'openai'}/{served}"
    note = f"本地部署「{item.name}」（{PROTOCOL_LABELS[wire]}）→ --model {model}；agent 经宿主机地址 {url} 访问"
    return ResolvedModel(model=model, env=env, secrets=[item.config.api_key] if item.config.api_key else [], notes=[note])


@lru_cache(maxsize=1)
def host_address() -> str:
    """宿主机在局域网上的地址。

    用「连一个不存在的外部地址」拿本机出口 IP —— UDP connect 不发包，
    只是让内核选路由，所以没有网络也不会阻塞。
    """
    import socket

    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
            sock.settimeout(0.2)
            sock.connect(("10.255.255.255", 1))
            address = sock.getsockname()[0]
        if address and not address.startswith("127."):
            return address
    except OSError:
        pass
    try:
        address = socket.gethostbyname(socket.gethostname())
        if address and not address.startswith("127."):
            return address
    except OSError:
        pass
    return "127.0.0.1"


def deployment_log(deployment_id: str, *, tail_bytes: int | None = None, offset: int = 0) -> dict:
    item = get_deployment(deployment_id)
    path = Path(item.log_file or "")
    if not path.is_file():
        return {"content": "", "size": 0, "offset": 0, "eof": not item.status.is_active}
    size = path.stat().st_size
    limit = tail_bytes or settings.log_tail_bytes
    with path.open("rb") as handle:
        if offset > 0:
            handle.seek(min(offset, size))
        elif size > limit:
            handle.seek(size - limit)
            handle.readline()
        data = handle.read()
    return {
        "content": data.decode("utf-8", errors="replace"),
        "size": size,
        "offset": size,
        "eof": not item.status.is_active,
    }


