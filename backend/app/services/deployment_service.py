AUTH_MIDDLEWARE = """\"\"\"PRT：Anthropic 客户端用 x-api-key 传密钥，vLLM 的鉴权只认 Authorization: Bearer。\"\"\"


class AnthropicApiKeyMiddleware:
    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope["type"] in ("http", "websocket"):
            headers = list(scope.get("headers") or [])
            if not any(name.lower() == b"authorization" for name, _ in headers):
                key = next((value for name, value in headers if name.lower() == b"x-api-key"), None)
                if key:
                    scope = dict(scope, headers=[*headers, (b"authorization", b"Bearer " + key)])
        await self.app(scope, receive, send)
"""

