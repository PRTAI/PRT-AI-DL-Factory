def create_deployment(payload: DeploymentCreate, *, owner: User) -> Deployment:
    extra = {key.lstrip("-").replace("-", "_") for key in payload.config.extra_args}
    if payload.api_protocol != "openai" and not payload.config.tool_call_parser.strip() and "tool_call_parser" not in extra:
        raise HTTPException(
            status.HTTP_400_BAD_REQUEST,
            detail=f"{PROTOCOL_LABELS[payload.api_protocol]} 接口主要给 codex / claude-code 用，"
            "它们依赖工具调用，请选择与模型匹配的工具调用解析器（tool_call_parser）",
        )
    model_path = _resolve_source(payload)
    with RESOURCE_LOCK:
        port = payload.port or _pick_port()
        _assert_port_free(port)
        gpu_ids = _allocate_gpus(payload.n_gpus)

        served = payload.served_model_name.strip() or Path(model_path).name
        deployment = Deployment(
            name=payload.name.strip(),
            note=payload.note,
            source=payload.source,
            model_id=payload.model_id,
            job_id=payload.job_id,
            model_path=model_path,
            served_model_name=served,
            port=port,
            api_protocol=payload.api_protocol,
            config=payload.config,
            owner_id=owner.id,
            owner_email=owner.email,
            project_id=payload.project_id,
            gpu_ids=gpu_ids,
        )
        if payload.config.tensor_parallel_size * payload.config.pipeline_parallel_size > max(len(gpu_ids), 1):
            raise HTTPException(
                status.HTTP_400_BAD_REQUEST,
                detail=(
                    f"tensor_parallel_size × pipeline_parallel_size = "
                    f"{payload.config.tensor_parallel_size * payload.config.pipeline_parallel_size}，"
                    f"但只申请了 {len(gpu_ids)} 张 GPU"
                ),
            )

        store.deployments.put(deployment)
    try:
        deployment = _launch(deployment)
    except Exception as exc:  # 启动失败也要留下记录，方便看日志排查
        _mark_failed(deployment.id, f"{type(exc).__name__}: {exc}")
        raise HTTPException(status.HTTP_400_BAD_REQUEST, detail=f"部署启动失败：{exc}") from exc

    audit_service.record(
        "deployment.create",
        actor=owner,
        target_type="deployment",
        target_id=deployment.id,
        summary=f"部署模型「{deployment.name}」于 {deployment.base_url}（{PROTOCOL_LABELS[deployment.api_protocol]}）",
        detail={"model_path": model_path, "gpus": gpu_ids, "api_protocol": deployment.api_protocol},
    )
    return deployment


def _resolve_source(payload: DeploymentCreate) -> str:
    if payload.source == DeploymentSource.MODEL:
        return model_service.resolve_model_path(payload.model_id, payload.model_path)
    if payload.source == DeploymentSource.JOB_OUTPUT:
        job = store.jobs.get(payload.job_id)
        if job is None:
            raise HTTPException(status.HTTP_404_NOT_FOUND, detail="来源任务不存在")
        candidate = Path(payload.model_path or job.runtime.output_dir or "")
        if not candidate.is_dir():
            raise HTTPException(status.HTTP_400_BAD_REQUEST, detail="该任务还没有可部署的产物目录")
        # LoRA adapter 目录不能直接给 vLLM 当 --model，必须先合并导出。
        if (candidate / "adapter_config.json").is_file():
            raise HTTPException(
                status.HTTP_400_BAD_REQUEST,
                detail="这是 LoRA adapter 目录，请先「合并导出」成完整权重再部署",
            )
        return str(candidate.resolve())
    candidate = Path(payload.model_path or "")
    if not candidate.is_dir():
        raise HTTPException(status.HTTP_400_BAD_REQUEST, detail=f"模型路径不存在：{payload.model_path}")
    return str(candidate.resolve())


def _pick_port() -> int:
    used = {item.port for item in store.deployments.find(lambda d: d.status.is_active)}
    for port in range(settings.deploy_port_start, settings.deploy_port_end + 1):
        if port not in used and not _port_in_use(port):
            return port
    raise HTTPException(
        status.HTTP_409_CONFLICT,
        detail=f"{settings.deploy_port_start}-{settings.deploy_port_end} 端口段已用满",
    )


def _assert_port_free(port: int) -> None:
    taken = store.deployments.first(lambda d: d.status.is_active and d.port == port)
    if taken is not None:
        raise HTTPException(status.HTTP_409_CONFLICT, detail=f"端口 {port} 已被部署「{taken.name}」占用")
    if _port_in_use(port):
        raise HTTPException(status.HTTP_409_CONFLICT, detail=f"端口 {port} 已被本机其他进程占用")


def _port_in_use(port: int) -> bool:
    import socket

    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        try:
            sock.bind(("127.0.0.1", port))
        except OSError:
            return True
    return False


def _allocate_gpus(n_gpus: int) -> list[int]:
    # 延迟导入：scheduler 会反过来问部署占了哪些 GPU。
    from .scheduler import scheduler

    total = scheduler.total_gpus
    if total == 0:
        return []
    if n_gpus > total:
        raise HTTPException(
            status.HTTP_400_BAD_REQUEST, detail=f"本机共有 {total} 张 GPU，无法申请 {n_gpus} 张"
        )
    free = scheduler.free_gpu_ids()  # 已经把训练任务和其他部署都算进去了
    if len(free) < n_gpus:
        raise HTTPException(
            status.HTTP_409_CONFLICT,
            detail=f"当前空闲 GPU 只有 {len(free)} 张（{free}），无法部署",
        )
    return free[:n_gpus]


def build_command(deployment: Deployment) -> tuple[list[str], dict[str, str]]:
    """vLLM 服务的 argv。参数名以 vllm.entrypoints.openai 为准。"""
    config = deployment.config
    command = [
        settings.python_for_vllm(),
        "-m",
        "vllm.entrypoints.openai.api_server",
        "--model",
        deployment.model_path,
        "--served-model-name",
        deployment.served_model_name,
        "--host",
        deployment.host,
        "--port",
        str(deployment.port),
        "--tensor-parallel-size",
        str(config.tensor_parallel_size),
        "--gpu-memory-utilization",
        str(config.gpu_memory_utilization),
        "--max-num-seqs",
        str(config.max_num_seqs),
        "--dtype",
        config.dtype,
    ]
    if config.pipeline_parallel_size > 1:
        command += ["--pipeline-parallel-size", str(config.pipeline_parallel_size)]
    if config.max_model_len:
        command += ["--max-model-len", str(config.max_model_len)]
    if config.quantization:
        command += ["--quantization", config.quantization]
    if config.trust_remote_code:
        command.append("--trust-remote-code")
    if config.enable_prefix_caching:
        command.append("--enable-prefix-caching")
    if config.enforce_eager:
        command.append("--enforce-eager")
    if config.chat_template:
        command += ["--chat-template", config.chat_template]
    if config.tool_call_parser.strip():
        command += ["--enable-auto-tool-choice", "--tool-call-parser", config.tool_call_parser.strip()]
    env = {"VLLM_WORKER_MULTIPROC_METHOD": "spawn"}
    if config.api_key:
        command += ["--api-key", config.api_key]
        if deployment.api_protocol == "anthropic":
            # 中间件模块由 _launch 写进工作目录
            command += ["--middleware", f"{Path(AUTH_MIDDLEWARE_FILE).stem}.AnthropicApiKeyMiddleware"]
            work_dir = str(settings.deployments_dir / deployment.id)
            env["PYTHONPATH"] = os.pathsep.join(filter(None, [work_dir, os.environ.get("PYTHONPATH", "")]))
    for key, value in config.extra_args.items():
        flag = key if key.startswith("-") else f"--{key.replace('_', '-')}"
        if value is True or value == "":
            command.append(flag)
        elif value is not False:
            command += [flag, str(value)]

    if deployment.gpu_ids:
        env["CUDA_VISIBLE_DEVICES"] = ",".join(str(i) for i in deployment.gpu_ids)
    return command, env


def _launch(deployment: Deployment) -> Deployment:
    work_dir = settings.deployments_dir / deployment.id
    work_dir.mkdir(parents=True, exist_ok=True)
    command, extra_env = build_command(deployment)
    if "--middleware" in command:
        (work_dir / AUTH_MIDDLEWARE_FILE).write_text(AUTH_MIDDLEWARE, encoding="utf-8")

    secrets = [deployment.config.api_key] if deployment.config.api_key else []
    masked = " ".join(shlex.quote(_mask(part, secrets)) for part in command)

    env = os.environ.copy()
    env.update(extra_env)
    env["PYTHONUNBUFFERED"] = "1"
    # vLLM 的 torch.compile 要调 ninja，它装在 vLLM 自己那个环境的 bin 里
    proc_env.with_interpreter_on_path(env, command[0])

    (work_dir / "run.sh").write_text(
        RUN_SH_TEMPLATE.format(
            dep_id=deployment.id,
            name=deployment.name,
            exports="\n".join(
                f"export {key}={shlex.quote(value)}" for key, value in sorted(extra_env.items())
            ),
            command=masked,
        ),
        encoding="utf-8",
    )
    (work_dir / "run.sh").chmod(0o750)
    (work_dir / "command.json").write_text(
        json.dumps(
            {"command": [_mask(p, secrets) for p in command], "env": extra_env},
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )

    log_path = work_dir / "stdout.log"
    log_handle = log_path.open("ab", buffering=0)
    log_handle.write(
        (
            f"=== PRT AI DL Factory — 模型部署 ===\n"
            f"deployment: {deployment.id} / {deployment.name}\n"
            f"model     : {deployment.model_path}\n"
            f"endpoint  : {deployment.base_url}（{PROTOCOL_LABELS[deployment.api_protocol]}）\n"
            f"gpus      : {deployment.gpu_ids or '(none)'}\n"
            f"command   : {masked}\n"
            f"{'=' * 70}\n\n"
        ).encode("utf-8")
    )

    process = subprocess.Popen(  # noqa: S603 - argv 由本模块构造，不过 shell
        command,
        cwd=str(work_dir),
        env=env,
        stdout=log_handle,
        stderr=subprocess.STDOUT,
        stdin=subprocess.DEVNULL,
        start_new_session=True,
    )
    with _LOCK:
        _PROCESSES[deployment.id] = process

    def mutate(item: Deployment) -> None:
        item.status = DeploymentStatus.STARTING
        item.work_dir = str(work_dir)
        item.log_file = str(log_path)
        item.command = masked
        item.pid = process.pid
        item.pgid = os.getpgid(process.pid)
        item.started_at = utcnow()
        item.stopped_at = None
        item.ready_at = None
        item.exit_code = None
        item.error = ""
        item.updated_at = utcnow()

    updated = store.deployments.update(deployment.id, mutate) or deployment
    threading.Thread(
        target=_supervise, args=(deployment.id, process, log_handle), daemon=True
    ).start()
    threading.Thread(target=_wait_ready, args=(deployment.id,), daemon=True).start()
    return updated


def _mask(value: str, secrets: list[str]) -> str:
    for secret in secrets:
        if secret and secret in value:
            value = value.replace(secret, "***")
    return value


# --------------------------------------------------------------------------- #
# Supervision
# --------------------------------------------------------------------------- #
def _supervise(deployment_id: str, process: subprocess.Popen, log_handle) -> None:
    exit_code = process.wait()
    try:
        log_handle.write(
            f"\n\n=== 进程结束，退出码 {exit_code} @ {utcnow().isoformat()} ===\n".encode("utf-8")
        )
        log_handle.close()
    except (OSError, ValueError):
        pass
    with _LOCK:
        _PROCESSES.pop(deployment_id, None)

    item = store.deployments.get(deployment_id)
    if item is None:
        return
    # 平台主动判失败（如所选接口路由不存在）后发的 SIGTERM 不能算用户停止
    stopped = item.status == DeploymentStatus.STOPPED or (item.status != DeploymentStatus.FAILED and exit_code in (
        -signal.SIGTERM,
        -signal.SIGKILL,
        143,
        137,
    ))

    def mutate(entry: Deployment) -> None:
        entry.exit_code = exit_code
        entry.stopped_at = utcnow()
        entry.gpu_ids = []
        entry.updated_at = utcnow()
        if stopped:
            entry.status = DeploymentStatus.STOPPED
        else:
            entry.status = DeploymentStatus.FAILED
            entry.error = entry.error or _tail(Path(entry.log_file))

    updated = store.deployments.update(deployment_id, mutate)
    if updated and updated.status == DeploymentStatus.FAILED:
        audit_service.notify(
            updated.owner_id,
            f"模型部署 {updated.name} 已退出",
            body=updated.error[:400],
            level="error",
            link="/deployments",
        )


def _wait_ready(deployment_id: str) -> None:
    """轮询 /v1/models：能列出模型、且所选接口路由存在才算真的可用。"""
    deadline = time.time() + READY_TIMEOUT_SECONDS
    while time.time() < deadline:
        item = store.deployments.get(deployment_id)
        if item is None or item.status in {DeploymentStatus.STOPPED, DeploymentStatus.FAILED}:
            return
        if _probe(item):
            if _promote(item):
                audit_service.notify(
                    item.owner_id,
                    f"模型部署 {item.name} 已就绪",
                    body=f"{item.base_url}（{PROTOCOL_LABELS[item.api_protocol]}，模型名 {item.served_model_name}）",
                    level="success",
                    link="/deployments",
                )
            return
        time.sleep(3.0)


def _promote(item: Deployment) -> bool:
    """服务已响应：确认所选接口存在后置为 serving；不存在就判失败并释放 GPU。"""
    missing = _missing_route(item)
    if not missing:
        store.deployments.update(item.id, _mark_serving)
        return True

    def mutate(entry: Deployment) -> None:
        entry.status = DeploymentStatus.FAILED
        entry.error = missing
        entry.updated_at = utcnow()

    store.deployments.update(item.id, mutate)
    _terminate(item)
    audit_service.notify(item.owner_id, f"模型部署 {item.name} 启动失败", body=missing, level="error", link="/deployments")
    return False


def _missing_route(item: Deployment) -> str:
    route = PROTOCOL_ROUTES.get(item.api_protocol)
    if not route:
        return ""
    try:
        with urllib.request.urlopen(f"http://127.0.0.1:{item.port}/openapi.json", timeout=10) as response:  # noqa: S310 - 本机回环
            paths = json.load(response).get("paths", {})
    except (urllib.error.URLError, OSError, ValueError, AttributeError):
        return ""  # 关了文档接口（--disable-fastapi-docs）就不校验，交给评测时暴露
    if route in paths:
        return ""
    return (
        f"当前 vLLM 没有提供 {route}，{PROTOCOL_LABELS[item.api_protocol]} 接口需要 vLLM ≥ 0.18；"
        "请升级部署环境的 vLLM，或改用 OpenAI Chat 接口"
    )


def _mark_serving(entry: Deployment) -> None:
    entry.status = DeploymentStatus.SERVING
    entry.ready_at = entry.ready_at or utcnow()
    entry.updated_at = utcnow()


def _probe(item: Deployment) -> bool:
    request = urllib.request.Request(f"http://127.0.0.1:{item.port}/v1/models")
    if item.config.api_key:
        request.add_header("Authorization", f"Bearer {item.config.api_key}")
    try:
        with urllib.request.urlopen(request, timeout=5) as response:  # noqa: S310 - 本机回环
            return response.status == 200
    except (urllib.error.URLError, OSError, ValueError):
        return False


def _tail(path: Path, lines: int = 40) -> str:
    if not path.is_file():
        return ""
    size = path.stat().st_size
    with path.open("rb") as handle:
        if size > 64_000:
            handle.seek(size - 64_000)
        text = handle.read().decode("utf-8", errors="replace")
    return "\n".join([line for line in text.splitlines() if line.strip()][-lines:])


def _mark_failed(deployment_id: str, message: str) -> None:
    def mutate(entry: Deployment) -> None:
        entry.status = DeploymentStatus.FAILED
        entry.error = message
        entry.gpu_ids = []
        entry.stopped_at = utcnow()
        entry.updated_at = utcnow()

    store.deployments.update(deployment_id, mutate)


