def stop_deployment(deployment_id: str, *, actor: User) -> Deployment:
    item = get_deployment(deployment_id)
    _assert_can_control(item, actor)
    if not item.status.is_active:
        raise HTTPException(status.HTTP_409_CONFLICT, detail="该部署已经停止")

    def mark_stopped(entry: Deployment) -> None:
        entry.status = DeploymentStatus.STOPPED
        entry.updated_at = utcnow()

    # 先落库再发信号：supervisor 线程靠这个状态区分「用户停的」和「自己崩的」。
    store.deployments.update(deployment_id, mark_stopped)
    _terminate(item)
    audit_service.record(
        "deployment.stop",
        actor=actor,
        target_type="deployment",
        target_id=deployment_id,
        summary=f"停止模型部署「{item.name}」",
    )
    return store.deployments.get(deployment_id) or item


def delete_deployment(deployment_id: str, *, actor: User) -> None:
    item = get_deployment(deployment_id)
    _assert_can_control(item, actor)
    if item.status.is_active:
        raise HTTPException(status.HTTP_409_CONFLICT, detail="请先停止再删除")
    store.deployments.delete(deployment_id)
    audit_service.record(
        "deployment.delete",
        actor=actor,
        target_type="deployment",
        target_id=deployment_id,
        summary=f"删除模型部署「{item.name}」",
    )


def _terminate(item: Deployment, *, grace_seconds: float = 20.0) -> None:
    def signal_group(sig: int) -> None:
        try:
            if item.pgid:
                os.killpg(item.pgid, sig)
            elif item.pid:
                os.kill(item.pid, sig)
        except (ProcessLookupError, PermissionError):
            pass

    signal_group(signal.SIGTERM)
    deadline = time.time() + grace_seconds
    while time.time() < deadline:
        if not is_alive(item):
            return
        time.sleep(0.5)
    signal_group(signal.SIGKILL)


def is_alive(item: Deployment) -> bool:
    with _LOCK:
        process = _PROCESSES.get(item.id)
    if process is not None:
        return process.poll() is None
    if not item.pid:
        return False
    try:
        proc = psutil.Process(item.pid)
        if proc.status() == psutil.STATUS_ZOMBIE:
            return False
        if item.started_at and proc.create_time() < item.started_at.timestamp() - 5:
            return False  # PID 复用
        return True
    except (psutil.NoSuchProcess, psutil.AccessDenied):
        return False


def reconcile() -> None:
    """平台重启后：进程没了的部署不能一直挂在 serving 上。"""
    for item in store.deployments.find(lambda d: d.status.is_active):
        if is_alive(item):
            if item.status == DeploymentStatus.STARTING and _probe(item):
                _promote(item)
            continue

        def mutate(entry: Deployment) -> None:
            entry.status = DeploymentStatus.FAILED
            entry.error = entry.error or "进程已不存在（可能在平台重启期间退出）"
            entry.gpu_ids = []
            entry.stopped_at = utcnow()
            entry.updated_at = utcnow()

        store.deployments.update(item.id, mutate)


def _assert_can_control(item: Deployment, actor: User) -> None:
    if actor.is_admin or item.owner_id == actor.id:
        return
    raise HTTPException(status.HTTP_403_FORBIDDEN, detail="只有部署的负责人或管理员可以操作")
