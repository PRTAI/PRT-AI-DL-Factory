# 部署选定的接口 → 评测时能接的 agent 接口。Responses 部署同端口仍有 chat/completions。
PROTOCOL_SUPPORT = {"openai": ("openai",), "responses": ("responses", "openai"), "anthropic": ("anthropic",)}
