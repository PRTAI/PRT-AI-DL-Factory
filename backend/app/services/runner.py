"""Process execution for jobs: materialise the work dir, spawn, supervise, kill.

Every job gets its own directory under ``data/jobs/<job_id>/``::

    run.sh          # reproducible launcher (secrets masked)
    command.json    # argv + env actually used (secrets masked)
    stdout.log      # merged stdout/stderr
    metrics.json    # parsed curves (written by the scheduler)
    outputs/        # checkpoints / harbor jobs dir
    <builder files> # train_config.yaml, generated scripts, …

The child is started with ``start_new_session=True`` so the whole process tree
(torchrun workers, ray actors, docker-driving harbor trials) can be signalled as
one process group.
"""

from __future__ import annotations

import json
import os
import shlex
import signal
import subprocess
import threading
import time
from pathlib import Path

import psutil

from ..builders import BuildError, build_job
from ..config import settings
from ..models import Job, JobStatus, utcnow
from ..store import store
from . import audit_service, proc_env

_PROCESSES: dict[str, subprocess.Popen] = {}
LIFECYCLE_LOCK = threading.RLock()

RUN_SH_TEMPLATE = """#!/usr/bin/env bash
# Generated by PRT AI DL Factory — job {job_id} ({job_name})
# Secrets are masked here; the platform injects the real values at runtime.
set -euo pipefail

cd {cwd}
{exports}
{preamble}
exec {command}
"""


def work_dir_for(job: Job) -> Path:
    return settings.jobs_dir / job.id


def output_dir_for(job: Job) -> Path:
    return settings.outputs_dir / job.id


def prepare(job: Job):
    """Build the command and materialise every file the run needs."""
    work_dir = work_dir_for(job)
    output_dir = output_dir_for(job)
    work_dir.mkdir(parents=True, exist_ok=True)
    output_dir.mkdir(parents=True, exist_ok=True)

    result = build_job(job, work_dir, output_dir)

    if job.harbor_action is not None and job.harbor_rerun is None:
        from . import harbor_action_service
        harbor_action_service.prepare_snapshot(
            job, work_dir, output_dir,
            selected_native=json.loads(result.files["selected-config.json"]) if "selected-config.json" in result.files else None,
        )

    for rel_path, content in result.files.items():
        target = work_dir / rel_path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")

    for extra_dir in result.mkdirs:
        Path(extra_dir).mkdir(parents=True, exist_ok=True)

    exports = "\n".join(
        f"export {key}={shlex.quote(value)}" for key, value in sorted(result.masked_env().items())
    )
    (work_dir / "run.sh").write_text(
        RUN_SH_TEMPLATE.format(
            job_id=job.id,
            job_name=job.name,
            cwd=shlex.quote(result.cwd),
            exports=exports,
            preamble="\n".join(f"mkdir -p {shlex.quote(d)}" for d in result.mkdirs),
            command=result.masked_command_line(),
        ),
        encoding="utf-8",
    )
    (work_dir / "run.sh").chmod(0o750)
    (work_dir / "command.json").write_text(
        json.dumps(
            {
                "command": [_mask(part, result.secrets) for part in result.command],
                "env": result.masked_env(),
                "cwd": result.cwd,
                "notes": result.notes,
            },
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )
    return result, work_dir, output_dir


def _mask(value: str, secrets: list[str]) -> str:
    for secret in secrets:
        if secret and secret in value:
            value = value.replace(secret, "***")
    return value


def launch(job: Job) -> Job:
    """Start the job process. Raises :class:`BuildError` on bad configuration."""
    with LIFECYCLE_LOCK:
        current = store.jobs.get(job.id)
        if current is None or current.runtime.cancel_requested or current.status.is_terminal:
            return current or job
    result, work_dir, output_dir = prepare(job)

    env = os.environ.copy()
    env.update(result.env)
    env.update(job.resources.env)
    env["PRT_JOB_ID"] = job.id
    env["PYTHONUNBUFFERED"] = "1"
    # 框架要在运行时 shell 出去调 torchrun / ray / ninja / deepspeed，
    # 这些装在它自己的 conda 环境里，不在平台的 PATH 上。
    proc_env.with_interpreter_on_path(env, result.command[0])
    if job.resources.gpu_ids:
        env["CUDA_VISIBLE_DEVICES"] = ",".join(str(i) for i in job.resources.gpu_ids)
    elif job.resources.n_gpus == 0:
        env["CUDA_VISIBLE_DEVICES"] = ""

    log_path = work_dir / "stdout.log"
    log_handle = log_path.open("ab", buffering=0)
    header = (
        f"=== PRT AI DL Factory ===\n"
        f"job    : {job.id} / {job.name}\n"
        f"type   : {job.type.value} ({job.framework.value})\n"
        f"owner  : {job.owner_email}\n"
        f"gpus   : {job.resources.gpu_ids or '(none)'}\n"
        f"cwd    : {result.cwd}\n"
        f"command: {result.masked_command_line()}\n"
        f"started: {utcnow().isoformat()}\n"
        f"{'=' * 70}\n\n"
    )
    log_handle.write(header.encode("utf-8"))

    # Cancellation and spawn+PID registration share this short critical section.
    # Preparation deliberately runs outside it so a slow build can be cancelled.
    with LIFECYCLE_LOCK:
        current = store.jobs.get(job.id)
        if current is None or current.runtime.cancel_requested or current.status.is_terminal:
            log_handle.close()
            return current or job
        try:
            process = subprocess.Popen(  # noqa: S603 - argv built by trusted builders
                result.command,
                cwd=result.cwd,
                env=env,
                stdout=log_handle,
                stderr=subprocess.STDOUT,
                stdin=subprocess.DEVNULL,
                start_new_session=True,
            )
        except (OSError, ValueError) as exc:
            log_handle.write(f"\n[launch failed] {exc}\n".encode("utf-8"))
            log_handle.close()
            raise BuildError(f"启动失败: {exc}") from exc

        _PROCESSES[job.id] = process

        def mutate(item: Job) -> None:
            item.status = JobStatus.RUNNING
            item.runtime.work_dir = str(work_dir)
            item.runtime.output_dir = result.output_dir or str(output_dir)
            item.runtime.log_file = str(log_path)
            item.runtime.script_path = str(work_dir / "run.sh")
            item.runtime.command = result.masked_command_line()
            item.runtime.pid = process.pid
            item.runtime.pgid = process.pid
            item.runtime.started_at = utcnow()
            item.runtime.finished_at = None
            item.runtime.exit_code = None
            item.runtime.error = ""
            item.progress.message = "已启动"
            item.updated_at = utcnow()

        updated = store.jobs.update(job.id, mutate) or job

    threading.Thread(target=_supervise, args=(job.id, process, log_handle), daemon=True).start()
    return updated


def _supervise(job_id: str, process: subprocess.Popen, log_handle) -> None:
    exit_code = process.wait()
    try:
        log_handle.write(f"\n\n=== 进程结束，退出码 {exit_code} @ {utcnow().isoformat()} ===\n".encode("utf-8"))
        log_handle.close()
    except (OSError, ValueError):
        pass
    job = store.jobs.get(job_id)
    if job is None:
        with LIFECYCLE_LOCK:
            _PROCESSES.pop(job_id, None)
        return

    def mutate(item: Job) -> None:
        item.runtime.exit_code = exit_code
        item.runtime.finished_at = utcnow()
        if item.runtime.cancel_requested or exit_code in (-signal.SIGTERM, -signal.SIGKILL, 143, 137):
            item.status = JobStatus.CANCELLED
            item.progress.message = "已终止"
        elif exit_code == 0:
            item.status = JobStatus.SUCCEEDED
            item.progress.percent = 100.0
            item.progress.message = "已完成"
        else:
            item.status = JobStatus.FAILED
            item.progress.message = f"失败（退出码 {exit_code}）"
            item.runtime.error = _tail_error(Path(item.runtime.log_file))
        item.updated_at = utcnow()

    # Keep ownership until the terminal status is persisted; reconciliation
    # must not mistake a just-exited child for a process lost on restart.
    with LIFECYCLE_LOCK:
        updated = store.jobs.update(job_id, mutate)
        _PROCESSES.pop(job_id, None)
    if updated is None:
        return

    # One last parse so the final step / trial counts are not left mid-flight.
    # Imported here because the scheduler imports this module.
    from .scheduler import refresh_metrics

    refreshed = refresh_metrics(updated)
    if refreshed.status.is_terminal:
        updated = refreshed

    level = {"succeeded": "success", "failed": "error", "cancelled": "warning"}.get(updated.status.value, "info")
    audit_service.notify(
        updated.owner_id,
        f"任务 {updated.name} {_STATUS_TEXT[updated.status]}",
        body=updated.runtime.error[:400] if updated.status == JobStatus.FAILED else updated.progress.message,
        level=level,
        link=f"/jobs/{updated.id}",
    )
    audit_service.record(
        f"job.{updated.status.value}",
        target_type="job",
        target_id=updated.id,
        summary=f"任务 {updated.name} {_STATUS_TEXT[updated.status]}（退出码 {exit_code}）",
    )


_STATUS_TEXT = {
    JobStatus.SUCCEEDED: "已完成",
    JobStatus.FAILED: "失败",
    JobStatus.CANCELLED: "已终止",
}


def _tail_error(log_path: Path, lines: int = 40) -> str:
    if not log_path.is_file():
        return ""
    size = log_path.stat().st_size
    with log_path.open("rb") as handle:
        if size > 64_000:
            handle.seek(size - 64_000)
        text = handle.read().decode("utf-8", errors="replace")
    tail = [line for line in text.splitlines() if line.strip()][-lines:]
    return "\n".join(tail)


def has_supervisor(job_id: str) -> bool:
    with LIFECYCLE_LOCK:
        return job_id in _PROCESSES


def is_running(job: Job) -> bool:
    with LIFECYCLE_LOCK:
        process = _PROCESSES.get(job.id)
    if process is not None:
        return process.poll() is None
    pid = job.runtime.pid
    if not pid:
        return False
    try:
        proc = psutil.Process(pid)
        if proc.status() == psutil.STATUS_ZOMBIE:
            return False
        # Guard against PID reuse: the process must have started no earlier
        # than the job did.
        if job.runtime.started_at and proc.create_time() < job.runtime.started_at.timestamp() - 5:
            return False
        return True
    except (psutil.NoSuchProcess, psutil.AccessDenied):
        return False


def terminate(job: Job, *, grace_seconds: float = 15.0) -> bool:
    """SIGTERM the process group, escalate to SIGKILL after ``grace_seconds``."""
    pgid = job.runtime.pgid
    pid = job.runtime.pid
    if not pgid and not pid:
        return False

    def signal_group(sig: int) -> bool:
        try:
            if pgid:
                os.killpg(pgid, sig)
            elif pid:
                os.kill(pid, sig)
            return True
        except (ProcessLookupError, PermissionError):
            return False

    signal_group(signal.SIGTERM)
    deadline = time.time() + grace_seconds
    while time.time() < deadline:
        if not is_running(job):
            return True
        time.sleep(0.5)
    signal_group(signal.SIGKILL)
    return True


def gpu_count() -> int:
    """Total GPUs visible to the platform (nvml, falling back to nvidia-smi)."""
    try:
        import pynvml

        pynvml.nvmlInit()
        try:
            return int(pynvml.nvmlDeviceGetCount())
        finally:
            pynvml.nvmlShutdown()
    except Exception:
        pass
    try:
        output = subprocess.run(
            ["nvidia-smi", "--list-gpus"], capture_output=True, text=True, timeout=10, check=False
        )
        return len([line for line in output.stdout.splitlines() if line.strip()])
    except (OSError, subprocess.SubprocessError):
        return 0
